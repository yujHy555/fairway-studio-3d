import { ClubSpec, ShotResult } from '../core/Types';
import { SURFACE_PROPERTIES, SurfaceType } from '../core/Constants';

export enum SwingPhase {
  IDLE = 'IDLE',
  BACKSWING = 'BACKSWING',   // Gauge rising to set power
  DOWNSWING = 'DOWNSWING',   // Gauge falling to snap accuracy
  COMPLETE = 'COMPLETE'
}

export class SwingEngine {
  public phase: SwingPhase = SwingPhase.IDLE;
  public powerPercent: number = 0;      // 0.0 to 1.15
  public accuracyOffset: number = 0;    // -1.0 (hook) to +1.0 (slice)

  private meterProgress: number = 0;    // 0 to 1
  private meterSpeed: number = 1.35;    // Cycles per second
  private activeClub: ClubSpec;
  private currentLie: SurfaceType = SurfaceType.TEE;

  // Aiming parameters
  public aimAzimuthDeg: number = 0;     // Heading in degrees
  public windSpeedMps: number = 3.5;    // Wind speed
  public windHeadingDeg: number = 45;   // Wind direction

  public onUpdate?: (meterValue: number, phase: SwingPhase) => void;
  public onShotExecute?: (shot: ShotResult) => void;

  constructor(initialClub: ClubSpec) {
    this.activeClub = initialClub;
  }

  public setClub(club: ClubSpec) {
    this.activeClub = club;
  }

  public setLie(lie: SurfaceType) {
    this.currentLie = lie;
  }

  /**
   * Primary action triggered by Spacebar, Click, or Tap
   */
  public handleActionClick(): SwingPhase {
    if (this.phase === SwingPhase.IDLE) {
      // 1st click: Start swing
      this.phase = SwingPhase.BACKSWING;
      this.meterProgress = 0;
      this.powerPercent = 0;
      this.accuracyOffset = 0;
      return this.phase;

    } else if (this.phase === SwingPhase.BACKSWING) {
      // 2nd click: Lock in power
      this.phase = SwingPhase.DOWNSWING;
      this.powerPercent = Math.min(1.15, this.meterProgress);
      return this.phase;

    } else if (this.phase === SwingPhase.DOWNSWING) {
      // 3rd click: Snap accuracy
      this.phase = SwingPhase.COMPLETE;

      // Accuracy: Target is 0.0 at the bottom.
      // Offset from zero defines draw/hook vs fade/slice
      const snapError = this.meterProgress; // 0 is perfect, >0 is late/early
      // Normalize snap error to -1 (hook) .. 0 (pure) .. +1 (slice)
      this.accuracyOffset = Math.max(-1.0, Math.min(1.0, snapError * 4.0));

      this.executeShot();
      return this.phase;
    }

    return this.phase;
  }

  public reset() {
    this.phase = SwingPhase.IDLE;
    this.meterProgress = 0;
    this.powerPercent = 0;
    this.accuracyOffset = 0;
    this.onUpdate?.(0, this.phase);
  }

  public update(dt: number) {
    if (this.phase === SwingPhase.BACKSWING) {
      this.meterProgress += this.meterSpeed * dt;
      if (this.meterProgress >= 1.15) {
        // Over-swing apex, start dropping down automatically
        this.meterProgress = 1.15;
        this.powerPercent = 1.0;
        this.phase = SwingPhase.DOWNSWING;
      }
      this.onUpdate?.(this.meterProgress, this.phase);

    } else if (this.phase === SwingPhase.DOWNSWING) {
      this.meterProgress -= this.meterSpeed * 1.5 * dt;
      if (this.meterProgress <= -0.25) {
        // Missed click! Terrible shank / top
        this.meterProgress = -0.25;
        this.accuracyOffset = 1.0;
        this.phase = SwingPhase.COMPLETE;
        this.executeShot();
      }
      this.onUpdate?.(this.meterProgress, this.phase);
    }
  }

  private executeShot() {
    const lieProps = SURFACE_PROPERTIES[this.currentLie];
    const power = this.powerPercent * lieProps.liePenalty;

    // Launch speed
    const launchSpeed = this.activeClub.baseBallSpeedMps * power;

    // Launch angle: club loft with subtle dynamic loft based on lie
    let launchAngle = this.activeClub.loftDegrees;
    if (this.activeClub.category === 'putter') {
      launchAngle = 2.0; // Putter rolls with minimal initial skip
    }

    // Backspin: scales with strike power and lie
    const backspin = this.activeClub.baseBackspinRPM * power * lieProps.spinMultiplier;

    // Sidespin: generated by mis-timed snap click
    const sidespin = this.activeClub.maxSidespinRPM * this.accuracyOffset;

    // Slight push/pull in launch azimuth from mis-hit
    const azimuthAdjustment = this.accuracyOffset * 4.0; // up to +/- 4 degrees push/pull
    const finalAzimuth = this.aimAzimuthDeg + azimuthAdjustment;

    const shot: ShotResult = {
      club: this.activeClub,
      powerPercent: power,
      accuracyOffset: this.accuracyOffset,
      launchAngleDeg: launchAngle,
      launchSpeedMps: launchSpeed,
      backspinRPM: backspin,
      sidespinRPM: sidespin,
      azimuthDeg: finalAzimuth,
      windSpeedMps: this.windSpeedMps,
      windHeadingDeg: this.windHeadingDeg
    };

    this.onShotExecute?.(shot);

    // Reset after shot is dispatched
    setTimeout(() => {
      this.reset();
    }, 1200);
  }
}
